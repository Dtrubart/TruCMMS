import fs from 'node:fs';
import assert from 'node:assert/strict';
import path from 'node:path';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.TRUCMMS_PLAYWRIGHT_MODULE || 'playwright');
const password = process.env.TRUCMMS_UI_PASSWORD;
assert.ok(password, 'Set TRUCMMS_UI_PASSWORD without putting credentials in source files.');
const username = process.env.TRUCMMS_UI_USER || 'Administrator';
const base = (process.env.TRUCMMS_BASE_URL || 'http://test.vanbags.localhost:8100').replace(/\/$/, '');
const expectedSite = new URL(base).hostname;
const artifacts = path.resolve(process.env.TRUCMMS_UI_ARTIFACT_DIR || 'test-results/ent002');
fs.mkdirSync(artifacts, {recursive:true});
const browser = await chromium.launch({channel: process.env.TRUCMMS_BROWSER_CHANNEL || (process.platform === 'win32' ? 'msedge' : undefined), headless: true, args: ['--host-resolver-rules=MAP *.vanbags.localhost 127.0.0.1']});
const context = await browser.newContext();
const errors = [], checks = [];
try {
 const page = await context.newPage();
 page.on('pageerror', e => errors.push(e.message));
 await page.goto(base+'/login');
 await page.locator('#login_email').fill(username);
 await page.locator('#login_password').fill(password);
 await page.locator('.btn-login:not(.btn-login-with-email-link)').click();
 await page.waitForURL(url => !url.pathname.includes('login'), {timeout: 60000});
 await page.goto(base+'/desk/trucmms-start');
 await page.waitForFunction(site => window.frappe?.boot?.sitename === site && frappe.csrf_token, expectedSite, {timeout:60000});
 const location = await page.evaluate(async () => {
  const {message: rows} = await frappe.call({method:'frappe.client.get_list', type:'GET', args:{doctype:'VB Equipment Location',fields:['name','company','site','location_name'],filters:{parent_location:['is','not set'],disabled:0},order_by:'name asc',limit_page_length:1}});
  if (!rows.length) throw new Error('No existing location available for read-only UI verification');
  return rows[0];
 });
 await page.evaluate(location => {frappe.route_options={company:location.company,site:location.site,location:location.name};frappe.set_route('trucmms-locations');}, location);
 await page.waitForSelector('.trucmms-locations h3', {timeout:60000});
 assert.equal(await page.locator('.trucmms-locations h3').innerText(), location.location_name);
 await page.locator('.trucmms-locations .tree').waitFor();
 const treeLocation = page.locator('.trucmms-locations .tree .tree-label').filter({hasText:location.location_name}).first();
 await treeLocation.waitFor({timeout:20000});
 assert.equal(await treeLocation.getAttribute('data-name'), location.name);
 await treeLocation.click();
 await page.waitForSelector('.trucmms-locations h3');
 assert.equal(await page.locator('.trucmms-locations h3').innerText(), location.location_name);
 checks.push('actual location node rendered and opened from tree, scoped breadcrumb');
 await page.getByRole('button',{name:'Cambiar jerarquía / estado',exact:true}).click();
 await page.locator('.modal:visible [data-fieldname="action"] select').selectOption('Reparent');
 await page.locator('.modal:visible [data-fieldname="reason"] textarea').fill('Read-only interface verification; do not confirm');
 assert.ok(await page.locator('.modal:visible').getByRole('button',{name:'Ver impacto',exact:true}).isVisible());
 await page.locator('.modal:visible .btn-modal-close').click();
 await page.locator('.modal:visible').waitFor({state:'hidden'});
 checks.push('controlled action dialog available without saving a change');
 await page.getByRole('button',{name:'Abrir ficha',exact:true}).click();
 await page.waitForFunction(name => window.cur_frm?.doctype === 'VB Equipment Location' && cur_frm.doc.name === name, location.name);
 await page.getByRole('button',{name:'Árbol de ubicaciones',exact:true}).waitFor();
 checks.push('native form returns to scoped tree');
 await page.getByRole('button',{name:'Árbol de ubicaciones',exact:true}).click();
 await page.waitForSelector('.trucmms-locations h3');
 const filter = page.locator('.page-form [data-fieldname="search"] input');
 await filter.fill(location.location_name); await filter.press('Tab');
 await page.waitForFunction(() => !document.querySelector('.trucmms-locations .tree'), {timeout:10000});
 await page.getByRole('button',{name:location.location_name,exact:true}).first().click();
 await page.waitForSelector('.trucmms-locations h3');
 checks.push('search preserves the chosen site and opens a record');
 await page.screenshot({path:path.join(artifacts, 'ent002-locations-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 // Native Desk opens its navigation overlay when shrinking from desktop.
 await page.mouse.click(375,400);
 await page.waitForTimeout(350);
 await page.locator('.trucmms-locations .location-panel').first().getByRole('button',{name:location.location_name,exact:true}).click();
 await page.waitForSelector('.trucmms-locations h3');
 await page.screenshot({path:path.join(artifacts, 'ent002-locations-mobile.png'),fullPage:true});
 const overflow = await page.locator('.trucmms-locations').evaluate(el => el.scrollWidth-el.clientWidth);
 assert.ok(overflow <= 2, 'Location view overflows on mobile');
 checks.push('390px responsive layout without horizontal overflow');
 assert.deepEqual(errors, []);
 const result={ok:true,checks,jsErrors:errors,mutations:0};
 fs.writeFileSync(path.join(artifacts, 'ent002-ui-results.json'),JSON.stringify(result,null,2));
 console.log(JSON.stringify(result));
} finally {await context.close();await browser.close();}
